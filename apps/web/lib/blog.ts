const isLive = (p: Post) => !!(p.slug && p.title) && p.published !== false;

/** Admin's posts if any were saved, otherwise the starter posts. Includes drafts. */
export async function getAllPosts(): Promise<{ posts: Post[]; usingDefaults: boolean }> {
  const saved = await getContent<Post[]>('blog');
  if (Array.isArray(saved) && saved.length) return { posts: saved, usingDefaults: false };
  return { posts: DEFAULT_POSTS, usingDefaults: true };
}

/** Published posts, newest first. */
export async function getPosts(): Promise<Post[]> {
  const { posts } = await getAllPosts();
  return posts.filter(isLive).sort((a, b) => (b.date ?? '').localeCompare(a.date ?? ''));
}

export async function getPost(slug: string): Promise<Post | undefined> {
  return (await getPosts()).find((p) => p.slug === slug);
}

/** Categories that actually have published posts, in the suggested order first. */
export function categoriesOf(posts: Post[]): string[] {
  const used = new Set(posts.map((p) => p.category).filter((c): c is string => !!c));
  return [...BLOG_CATEGORIES.filter((c) => used.has(c)), ...[...used].filter((c) => !BLOG_CATEGORIES.includes(c))];
}

export const postUrl = (p: Post) => `${SITE_URL}/blog/${p.slug}`;

/** "1688/Taobao গাইড" → "1688-taobao-গাইড": no ?category= in links, so Google sees one clean page per category. */
const BLOG_CAT_SLUG: Record<string, string> = {
  'চীন থেকে পণ্য আমদানি': 'china-import',
  'শিপিং গাইড': 'shipping-guide',
  '1688/Taobao গাইড': '1688-taobao-guide',
  'ব্যবসার টিপস': 'business-tips',
};
export const blogCategorySlug = (c: string) => BLOG_CAT_SLUG[c] ?? c.toLowerCase().replace(/[^\p{L}\p{M}\p{N}]+/gu, '-').replace(/^-+|-+$/g, '');
export const blogCategoryPath = (c: string) => `/blog/category/${encodeURIComponent(blogCategorySlug(c))}`;

/** Reading time in minutes (Bangla text, ~200 words/min). */
export const readMinutes = (body = '') => Math.max(1, Math.round(body.split(/\s+/).filter(Boolean).length / 200));
